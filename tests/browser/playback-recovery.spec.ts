import { expect } from '@playwright/test';
import { test } from './app-fixture';

for (const width of [1440, 390]) test(`playback problems show distinct reasons and recovery only when needed without losing browsing at ${width}px`, async ({ page, context, isolatedApp }) => {
  await page.setViewportSize({ width, height: 900 });
  const { manager, remote } = isolatedApp;
  await manager.save(remote.origin, 'fixture-token', 0);
  await manager.selectDestination('sonos:room', manager.view().revision);
  const post = (path: string, data: unknown) => page.request.post(path, { data, headers: { Origin: isolatedApp.origin } });
  const joined = await (await post('/api/participant/join', { pin: '1234', nickname: 'Current listener' })).json();
  const found = await (await post('/api/participant/search', { turnId: joined.turnId, query: 'fixture' })).json();
  const start = () => post('/api/participant/play', { turnId: joined.turnId, previousPlaybackId: null, trackId: found.tracks[0].id });
  expect((await start()).ok()).toBe(true);
  const host = await context.newPage(); await host.setViewportSize({ width, height: 900 });
  await page.goto('/participant'); await host.goto('/host');
  const input = page.getByRole('searchbox', { name: 'Search catalogue' });
  await input.fill('Keep this private search');
  await input.evaluate(node => { (window as unknown as { originalSearch: Element }).originalSearch = node; });
  const writesBefore = remote.calls.filter(call => /player_queues\/(play_media|pause|resume|stop)$/.test(call.command)).length;
  remote.failReads('player_queues/get_active_queue', 2); remote.notify();
  const readsBefore = remote.calls.filter(call => call.command === 'player_queues/get_active_queue').length;
  await expect.poll(() => remote.calls.filter(call => call.command === 'player_queues/get_active_queue').length).toBeGreaterThanOrEqual(readsBefore + 3);
  expect(isolatedApp.engine.ready).toBe(true);
  await expect(page.locator('[data-playback-problem]')).toHaveCount(0);
  expect(remote.calls.filter(call => /player_queues\/(play_media|pause|resume|stop)$/.test(call.command))).toHaveLength(writesBefore);
  await expect(input).toBeFocused(); await expect(input).toHaveValue('Keep this private search');
  const beforeExternal = remote.calls.filter(call => call.command === 'player_queues/stop').length;
  remote.queue.current_item!.queue_item_id = 'another-source'; remote.notify();
  const warning = page.locator('[data-playback-problem]');
  await expect(warning).toHaveAttribute('data-playback-problem', 'external-playback');
  await expect(warning).toContainText('Playback changed outside this app');
  await expect(warning).not.toContainText('recover controls');
  await expect(host.locator('[data-playback-problem]')).not.toContainText('Recover controls in Settings');
  expect(remote.calls.filter(call => call.command === 'player_queues/stop')).toHaveLength(beforeExternal);
  const settings = await context.newPage(); await settings.setViewportSize({ width, height: 900 }); await settings.goto('/host/settings');
  await expect(settings.locator('.settings-recovery')).toContainText('Playback changed outside this app');
  await expect(settings.getByRole('button', { name: 'Recover playback controls', exact: true })).toHaveCount(0);
  expect((await start()).ok()).toBe(true);
  // Settings also reads the queue; keep authorization unavailable until the
  // playback monitor observes it rather than racing for a single failed read.
  remote.failReads('player_queues/get_active_queue', 100, 401); remote.notify();
  await expect(warning).toHaveAttribute('data-playback-problem', 'authorization');
  await expect(warning).toContainText('Music Assistant rejected this app’s access');
  await expect(warning).toContainText('Ask the host to recover controls');
  await expect(host.getByRole('link', { name: 'Recover controls in Settings', exact: true })).toBeVisible();
  await expect(settings.locator('.settings-recovery')).toContainText('Music Assistant rejected this app’s access');
  await settings.locator('.settings-recovery summary').click();
  await expect(settings.locator('.settings-recovery')).toContainText('Diagnostic code: authorization');
  await expect(input).toBeFocused(); await expect(input).toHaveValue('Keep this private search');
  expect(await input.evaluate(node => node === (window as unknown as { originalSearch: Element }).originalSearch)).toBe(true);
  expect(isolatedApp.engine.view({ kind: 'host' }).turnId).toBe(joined.turnId);
  remote.failReads('player_queues/get_active_queue', 0);
  settings.once('dialog', dialog => dialog.accept());
  await settings.getByRole('button', { name: 'Recover playback controls', exact: true }).click();
  await expect(warning).toHaveCount(0);
  await expect(page.locator('#player-transport')).toBeDisabled();
  await expect(input).toHaveValue('Keep this private search');
  for (const current of [page, host, settings]) expect(await current.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
